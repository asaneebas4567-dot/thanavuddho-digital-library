/**
 * ระบบวิเคราะห์คำถามเชิงสถานการณ์และจริยธรรมชีวิต (Situational & Ethics Guardrail)
 * ดูแลคำถามละเอียดอ่อน เช่น การถอดเครื่องช่วยหายใจ, การแพทย์, ความสูญเสีย, ภาวะซึมเศร้า
 * เน้นการปลอบประโลม เห็นอกเห็นใจ แยกแยะประเด็นธรรมะกับการแพทย์ และไม่ตัดสินคนว่าบาป
 */

import { normalizeThaiText } from './thaiTokenizer';

export type CriticalTopicType = 'medical_end_of_life' | 'severe_grief_loss' | 'suicide_crisis' | 'none';

export interface SituationalAnalysisResult {
  isCritical: boolean;
  topicType: CriticalTopicType;
  empathyOpening: string;
  medicalBoundaryNotice?: string;
  guidingEthicalPrinciples: string[];
  actionRecommendation: string;
}

/**
 * วิเคราะห์ว่าคำถามเป็นประเด็นละเอียดอ่อนหรือคำถามชีวิตที่ต้องระมัดระวังหรือไม่
 */
export function analyzeSituationalQuestion(query: string): SituationalAnalysisResult {
  const normQ = normalizeThaiText(query);

  // 1. กรณี: การแพทย์และวาระสุดท้ายของชีวิต (เช่น ถอดเครื่องช่วยหายใจ, ท่อช่วยหายใจ, Living will)
  const isMedicalEndOfLife = [
    'ถอดเครื่องช่วยหายใจ', 'เครื่องช่วยหายใจ', 'ท่อช่วยหายใจ', 'ถอดท่อ',
    'วาระสุดท้าย', 'กำลังจะเสียชีวิต', 'สมองตาย', 'ยื้อชีวิต', 'ปล่อยให้ไปสบาย', 
    'จะบาปไหม', 'living will', 'พินัยกรรมชีวิต', 'การุณยฆาต', 'euthanasia',
    'ปั๊มหัวใจ', 'cpr', 'ฉีดยาให้ไปสงบ', 'ฉีดยาให้ตาย'
  ].some(k => normQ.includes(k) || (normQ.includes('ถอด') && (normQ.includes('เครื่อง') || normQ.includes('ท่อ'))));

  if (isMedicalEndOfLife) {
    return {
      isCritical: true,
      topicType: 'medical_end_of_life',
      empathyOpening: 'อาตมภาพและระบบห้องสมุดขอส่งกำลังใจและแสดงความเห็นอกเห็นใจอย่างยิ่งต่อท่านและครอบครัว ในช่วงเวลาที่ต้องเผชิญกับการตัดสินใจที่ยากลำบากและละเอียดอ่อนต่อจิตใจเช่นนี้',
      medicalBoundaryNotice: '⚠️ **ข้อพึงตระหนัก:** การประเมินสภาพร่างกาย การทำงานของสมอง และแนวทางการรักษา เป็นดุลยพินิจของคณะแพทย์ผู้เชี่ยวชาญร่วมกับครอบครัว ระบบธรรมะนี้มีหน้าที่ให้แง่คิดทางศีลธรรมและจิตใจเท่านั้น มิอาจก้าวล่วงหรือตัดสินใจแทนทีมแพทย์ได้',
      guidingEthicalPrinciples: [
        '**กรรมอยู่ที่เจตนา (เจตนาหัง ภิกขเว กัมมัง วทามิ):** ในทางพระพุทธศาสนา การจะผิดศีลข้อ ๑ (ปาณาติบาต) ต้องประกอบด้วย "จิตคิดจะฆ่าด้วยความพยาบาทหรือความเกลียดชัง" หากการตัดสินใจของแพทย์และญาติเกิดขึ้นเพื่อยุติความทรมานทางกายตามกระบวนการธรรมชาติ โดยมิได้มีจิตมุ่งร้ายเพื่อทำลายชีวิต ย่อมมิใช่จิตบาป และห้ามตัดสินว่าครอบครัวเป็นผู้มีบาป',
        '**ช่วยประคองจิตผู้ป่วยให้ผ่องใส (จิตเต อสังกิลิฏเฐ สุคติ ปาฏิกังขา):** ในวาระสุดท้ายของชีวิต จิตดวงสุดท้าย (จุติจิต) มีความสำคัญยิ่ง สิ่งประเสริฐที่สุดที่ญาติสามารถทำให้ได้ คือการสร้างบรรยากาศแห่งความสงบสุข เปิดเสียงสวดมนต์ แผ่เมตตา หรือพูดคุยข้างหูเตือนให้นึกถึงคุณงามความดีและบุญกุศลที่ท่านเคยทำมาตลอดชีวิต',
        '**การปล่อยวางและระงับความโศกเศร้า:** ทุกชีวิตต้องดำเนินไปตามกฎแห่งไตรลักษณ์ (อนิจจัง ทุกขัง อนัตตา) การส่งท่านด้วยจิตที่เปี่ยมด้วยความรัก ความกตัญญู และความผ่องใส จะเป็นพลังเกื้อหนุนดวงวิญญาณสู่สุคติภูมิได้ดีที่สุด'
      ],
      actionRecommendation: 'หากครอบครัวยังมีความลังเลใจ ขอแนะนำให้ปรึกษาหารือกับทีมแพทย์ผู้รักษาอย่างรอบคอบ เพื่อเข้าใจข้อเท็จจริงทางการแพทย์ และพร้อมกับนิมนต์พระอาจารย์หรือผู้รู้ทางธรรมเพื่อช่วยนำสวดมนต์และทำจิตใจให้สงบ'
    };
  }

  // 2. กรณี: ความสูญเสียและโศกเศร้าอย่างรุนแรง (Grief & Loss)
  const isLossOfLovedOne = [
    'คนรักตาย', 'พ่อตาย', 'แม่ตาย', 'ลูกตาย', 'สูญเสียคนรัก', 'ทำใจไม่ได้',
    'คิดถึงคนที่ตาย', 'อยากตายตาม', 'หัวใจสลาย'
  ].some(k => normQ.includes(k));

  if (isLossOfLovedOne) {
    return {
      isCritical: true,
      topicType: 'severe_grief_loss',
      empathyOpening: 'ขอแสดงความเสียใจและส่งความปรารถนาดีต่อหัวใจของท่านอย่างสุดซึ้ง ความสูญเสียบุคคลอันเป็นที่รักยิ่งคือบททดสอบอันยิ่งใหญ่ของจิตใจมนุษย์',
      guidingEthicalPrinciples: [
        'ความพลัดพรากจากของรักของชอบใจเป็นธรรมดาของสังสารวัฏ แม้แต่พระสัมมาสัมพุทธเจ้าก็ทรงแสดงธรรมว่าสิ่งใดเกิด สิ่งนั้นย่อมดับไปเป็นธรรมดา',
        'สายใยความผูกพันที่แท้จริงคือ "บุญกุศล" การตั้งใจทำทาน รักษาศีล และเจริญสมาธิภาวนา แล้วอุทิศส่วนบุญไปให้ คือของขวัญอันทรงคุณค่าที่สุดที่เชื่อมโยงถึงผู้ล่วงลับ'
      ],
      actionRecommendation: 'อนุญาตให้ตนเองได้พักผ่อนและร้องไห้ได้ตามธรรมชาติ แล้วค่อยๆ สูดลมหายใจลึกๆ นำใจมาพักไว้ในจุดที่สบาย นึกถึงรอยยิ้มและความดีงามของท่านเพื่อเป็นแรงผลักดันในการสร้างคุณประโยชน์ต่อไป'
    };
  }

  return {
    isCritical: false,
    topicType: 'none',
    empathyOpening: '',
    guidingEthicalPrinciples: [],
    actionRecommendation: ''
  };
}
