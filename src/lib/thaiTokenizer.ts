/**
 * ปรับข้อความให้อยู่ในรูปมาตรฐาน (ตัดวรรณยุกต์ซ้ำ, แปลงเป็นตัวพิมพ์เล็ก, ตัดช่องว่างหัวท้าย)
 */
export function normalizeThaiText(text: string): string {
  if (!text) return '';
  return text
    .trim()
    .toLowerCase()
    .replace(/[\u200B-\u200D\uFEFF]/g, '') // ตัด Zero-width spaces
    .replace(/\s+/g, ' ');
}

/**
 * ตัดคำภาษาไทยโดยใช้ Intl.Segmenter มาตรฐาน
 */
export function tokenizeThai(text: string): string[] {
  const norm = normalizeThaiText(text);
  if (!norm) return [];

  // ตรวจสอบว่า Runtime รองรับ Intl.Segmenter หรือไม่
  if (typeof Intl !== 'undefined' && 'Segmenter' in Intl) {
    try {
      const segmenter = new (Intl as any).Segmenter('th', { granularity: 'word' });
      const tokens: string[] = [];
      for (const segment of segmenter.segment(norm)) {
        const word = segment.segment.trim();
        // Allow meaningful tokens length >= 2 (e.g. 'ใจ', 'สุข', 'บุญ') and numbers
        if (word && (word.length >= 2 || /\d|[๐-๙]/.test(word)) && !THAI_STOPWORDS.has(word)) {
          tokens.push(word);
        }
      }
      return tokens;
    } catch {
      // Fallback ถ้ามี error
    }
  }

  // Fallback พื้นฐานแยกด้วยช่องว่าง
  return norm.split(/\s+/).filter(w => w.length >= 2 && !THAI_STOPWORDS.has(w));
}

/**
 * ขยายคำค้นด้วยคำพ้องความหมายทางธรรมะ
 */
export function expandKeywordsWithSynonyms(tokens: string[]): string[] {
  const expanded = new Set<string>(tokens);

  for (const token of tokens) {
    for (const [key, synonyms] of Object.entries(DHAMMA_SYNONYMS)) {
      if (token.includes(key) || key.includes(token) || synonyms.some(s => s.includes(token) || token.includes(s))) {
        expanded.add(key);
        synonyms.forEach(s => expanded.add(s));
      }
    }
  }

  return Array.from(expanded);
}

