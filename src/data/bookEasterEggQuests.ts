/**
 * ดึงเควสของหนังสือเล่มที่ระบุ
 */
export function getBookQuests(bookId: string): BookEasterEggQuest[] {
  return bookEasterEggQuests[bookId] || [];
}

/**
 * ตรวจสอบว่าในหน้าที่กำหนดมีเควสเริ่มทำงานหรือไม่
 */
export function findQuestByPage(bookId: string, page: number): BookEasterEggQuest | null {
  const quests = getBookQuests(bookId);
  return quests.find(q => {
    const end = q.triggerPageEnd ?? q.triggerPage;
    return page >= q.triggerPage && page <= end;
  }) || null;
}

/**
 * ดึงเควสทั้งหมดจากทุกเล่มพร้อมชื่อหนังสือ
 */
export function getAllQuestsAcrossBooks(): (BookEasterEggQuest & { bookTitle: string; bookCover: string })[] {
  const all: (BookEasterEggQuest & { bookTitle: string; bookCover: string })[] = [];
  for (const [bookId, list] of Object.entries(bookEasterEggQuests)) {
    const info = QUEST_BOOKS_CATALOG[bookId] || { title: bookId, coverImage: '/images/books/book-placeholder.jpg' };
    list.forEach(q => {
      all.push({
        ...q,
        bookTitle: info.title,
        bookCover: info.coverImage
      });
    });
  }
  return all;
}

/**
 * คำนวณความคืบหน้ารวมจาก localStorage ของผู้ใช้ (คะแนนสะสม, เควสที่ค้นพบ, เควสที่สำเร็จ)
 */
export function getGlobalUserQuestProgress() {
  if (typeof window === 'undefined') {
    return {
      totalPoints: 0,
      completedQuestIds: [] as string[],
      discoveredQuestIds: [] as string[],
      discoveredQuests: [] as (BookEasterEggQuest & { bookTitle: string; isCompleted: boolean })[],
      allQuestsCount: 0
    };
  }

  const allQuests = getAllQuestsAcrossBooks();
  const completedIds: string[] = [];
  const discoveredIds: string[] = [];

  for (const bookId of Object.keys(bookEasterEggQuests)) {
    try {
      const savedCompleted = localStorage.getItem(`dhamma_quests_${bookId}`);
      if (savedCompleted) {
        const parsed = JSON.parse(savedCompleted);
        if (Array.isArray(parsed)) {
          parsed.forEach(id => {
            if (!completedIds.includes(id)) completedIds.push(id);
            if (!discoveredIds.includes(id)) discoveredIds.push(id);
          });
        }
      }

      const savedDiscovered = localStorage.getItem(`dhamma_discovered_${bookId}`);
      if (savedDiscovered) {
        const parsed = JSON.parse(savedDiscovered);
        if (Array.isArray(parsed)) {
          parsed.forEach(id => {
            if (!discoveredIds.includes(id)) discoveredIds.push(id);
          });
        }
      }
    } catch {
      // ignore JSON parse error
    }
  }

  // Calculate total points
  const totalPoints = completedIds.reduce((sum, qId) => {
    const q = allQuests.find(item => item.id === qId);
    return sum + (q?.loot.points || 0);
  }, 0);

  // Filter discovered quests list
  const discoveredQuests = allQuests
    .filter(q => discoveredIds.includes(q.id))
    .map(q => ({
      ...q,
      isCompleted: completedIds.includes(q.id)
    }));

  return {
    totalPoints,
    completedQuestIds: completedIds,
    discoveredQuestIds: discoveredIds,
    discoveredQuests,
    allQuestsCount: allQuests.length
  };
}
